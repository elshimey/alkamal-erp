export const tourById = (id: string) => TOURS.find((t) => t.id === id);

/** هل الصفحة الحالية هي صفحة الخطوة؟ [id] تطابق أي جزء. */
export function matchPath(pattern: string, pathname: string) {
  const re = new RegExp(`^${pattern.replace(/\[[^\]]+\]/g, "[^/]+")}/?$`);
  return re.test(pathname);
}

/** جولات الشاشة الحالية لزر «كيف أعمل هذا؟»، كل منها من أول خطوة لها في هذه الشاشة. */
export function toursForPath(pathname: string) {
  return TOURS.filter((t) => t.screens.some((s) => matchPath(s, pathname))).map((tour) => {
    const step = tour.steps.findIndex((s) => matchPath(s.path, pathname));
    return { tour, step: step < 0 ? 0 : step };
  });
}
