/** هل الصفحة الحالية هي صفحة الخطوة؟ [id] تطابق أي جزء. */
export function matchPath(pattern: string, pathname: string) {
  const re = new RegExp(`^${pattern.replace(/\[[^\]]+\]/g, "[^/]+")}/?$`);
  return re.test(pathname);
}
