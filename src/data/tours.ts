// دليل الدورات المستندية التفاعلي: كل دورة خطوات مرقمة تنتقل بين الصفحات،
// تضيء البند المطلوب وتشرح ما تفعله ولماذا محاسبياً، وتختم بالقيود التي تكوّنت.
import type { IconName } from "@/components/icons";

/** البند الذي يُضاء: محدد CSS، أو نص ظاهر داخل وسم معين. up يوسّع الإضاءة إلى أقرب أب. */
export interface TourTarget {
  css?: string;
  text?: string;
  tag?: string;
  up?: string;
}

export interface EntryLine {
  side: "dr" | "cr";
  account: string;
  note?: string;
}

export interface TourStep {
  /** الصفحة التي يظهر عليها البند؛ [id] تطابق أي رقم */
  path: string;
  /** رابط الانتقال إن كان المستخدم في صفحة أخرى (الافتراضي path) */
  href?: string;
  /** اسم الصفحة كما يظهر في زر الانتقال */
  page: string;
  target?: TourTarget;
  title: string;
  body: string;
  accounting?: string;
  entry?: EntryLine[];
  /** click: تنتقل الجولة عند الضغط على البند نفسه؛ next: بزر «التالي» */
  advance?: "click" | "next";
}

export interface Tour {
  id: string;
  title: string;
  icon: IconName;
  summary: string;
  steps: TourStep[];
  /** القيود التي تكوّنت في الدورة كلها، تُعرض في الختام */
  entries: { title: string; lines: EntryLine[] }[];
  /** تنبيه للمستشار المالي: بند ناقص أو أكثر من آلية */
  note?: string;
}

const text = (t: string, tag = "h2", up?: string): TourTarget => ({ text: t, tag, up });
const card = (t: string): TourTarget => text(t, "h2", "section");
const panel = (t: string): TourTarget => text(t, "summary span", "details");
const button = (t: string): TourTarget => text(t, "button");
const css = (c: string, up?: string): TourTarget => ({ css: c, up });
const firstRow = (href?: string): TourTarget => css(href ? `table tbody a[href^="${href}"]` : "table tbody tr");

