/** البند الذي يُضاء: خانة بعنوانها، أو قسم في النافذة، أو محدد CSS، أو نص ظاهر داخل وسم. up يوسّع الإضاءة لأقرب أب. */
export interface TourTarget {
  field?: string;
  section?: string;
  css?: string;
  text?: string;
  tag?: string;
  up?: string;
}

export interface EntryLine {
  side: "dr" | "cr";
  account: string;
  note?: string;
}

export interface TourStep {
  /** الصفحة التي يظهر عليها البند؛ [id] تطابق أي رقم */
  path: string;
  /** رابط فتحها (مع النافذة مثلاً ?new=1). الافتراضي path */
  href?: string;
  /** اسم الصفحة كما يظهر في زر «افتح» */
  page: string;
  target?: TourTarget;
  title: string;
  body: string;
  /** شرح محاسبي وقيد، مطويان خلف «اعرض القيد» */
  accounting?: string;
  entry?: EntryLine[];
  /** click: بالضغط على البند؛ fill: حين تُملأ الخانة؛ next (الافتراضي): بزر «التالي» */
  advance?: "click" | "next" | "fill";
  /** خانة اختيارية: زر «تخطٍّ» */
  optional?: boolean;
  /** القسم الذي تنتمي له الخطوة: «أعرف هذا» يقفز لأول خطوة بعده */
  group?: string;
  /** رسالة بديلة حين لا يظهر البند */
  missing?: string;
}

export type TourGroup = "البداية" | "الأسطول" | "الصيانة" | "المبيعات" | "المشتريات" | "المخزون" | "الموارد البشرية" | "المحاسبة";
export const TOUR_GROUPS: TourGroup[] = ["البداية", "الأسطول", "الصيانة", "المبيعات", "المشتريات", "المخزون", "الموارد البشرية", "المحاسبة"];

export interface Tour {
  id: string;
  group: TourGroup;
  title: string;
  icon: IconName;
  summary: string;
  /** الشاشات التي يظهر فيها زر «كيف أعمل هذا؟» لهذه الجولة */
  screens: string[];
  steps: TourStep[];
  /** القيود التي تتكوّن في هذه الدورة (تُعرض في الختام إن لم يتكوّن قيد فعلي) */
  entries: { title: string; lines: EntryLine[] }[];
  note?: string;
}

// ——— أدوات قصيرة لكتابة الخطوات ———
const F = (field: string): TourTarget => ({ field });
const S = (section: string): TourTarget => ({ section });
const B = (text: string): TourTarget => ({ text, tag: "button" });
const L = (text: string): TourTarget => ({ text, tag: "a" });
const H = (text: string, up = "section"): TourTarget => ({ text, tag: "h2", up });
const C = (css: string, up?: string): TourTarget => ({ css, up });
const SHEET = C('[data-tour="sheet"]');
const MENU = (text: string): TourTarget => ({ text, tag: '[role="menuitem"]' });
type X = Partial<TourStep>;
const at = (path: string, page: string, href?: string) => ({
  /** خطوة شرح أو زر «التالي» */
  info: (target: TourTarget | undefined, title: string, body: string, x: X = {}): TourStep => ({ path, href, page, target, title, body, ...x }),
  /** ينتظر الضغط على البند */
  click: (target: TourTarget, title: string, body: string, x: X = {}): TourStep => ({ path, href, page, target, title, body, advance: "click", ...x }),
  /** ينتظر ملء الخانة */
  fill: (field: string, title: string, body: string, x: X = {}): TourStep => ({ path, href, page, target: F(field), title, body, advance: "fill", ...x }),
});
const dr = (account: string, note?: string): EntryLine => ({ side: "dr", account, note });
const cr = (account: string, note?: string): EntryLine => ({ side: "cr", account, note });
const SAVE = B("حفظ");

