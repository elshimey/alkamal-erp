// توحيد الكتابة: الهمزات والتاء المربوطة والألف المقصورة والمسافات
const norm = (s: string) =>
  s
    .trim()
    .replace(/[أإآ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/\s+/g, " ");

const INDEX = new Map(Object.entries(CITIES).map(([k, v]) => [norm(k), v]));

/** إحداثيات المدينة، أو مركز دولتها مع إزاحة ثابتة صغيرة حتى لا تتطابق مدينتان مجهولتان. */
export function cityPoint(name: string, country: string): [number, number] {
  const hit = INDEX.get(norm(name)) ?? INDEX.get(norm(name).replace(/^ال/, ""));
  if (hit) return hit;
  const [lat, lon] = COUNTRIES[country] ?? COUNTRIES.SA;
  let h = 0;
  for (const ch of name) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return [
    lat + ((h % 100) / 100 - 0.5) * 1.6,
    lon + (((h >> 8) % 100) / 100 - 0.5) * 1.6,
  ];
}
